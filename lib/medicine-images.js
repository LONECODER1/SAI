/**
 * Returns the best matching medicine image URL for a given product
 */
export function getMedicineImageUrl(product) {
  if (!product) {
    return CATEGORY_IMAGE_FALLBACKS["General Healthcare"];
  }

  // 1. Direct product.imageUrl if already provided and valid
  if (product.imageUrl && product.imageUrl.startsWith("http")) {
    return product.imageUrl;
  }

  // 2. Exact or fuzzy match on product name
  const nameKey = (product.name || "").toLowerCase().trim();
  if (MEDICINE_IMAGE_MAP[nameKey]) {
    return MEDICINE_IMAGE_MAP[nameKey];
  }

  for (const [key, url] of Object.entries(MEDICINE_IMAGE_MAP)) {
    if (nameKey.includes(key) || key.includes(nameKey)) {
      return url;
    }
  }

  // 3. Match on generic name
  const genericKey = (product.genericName || "").toLowerCase().trim();
  if (genericKey) {
    for (const [key, url] of Object.entries(MEDICINE_IMAGE_MAP)) {
      if (genericKey.includes(key) || key.includes(genericKey)) {
        return url;
      }
    }
  }

  // 4. Match on category
  const cat = product.category || "General Healthcare";
  if (CATEGORY_IMAGE_FALLBACKS[cat]) {
    return CATEGORY_IMAGE_FALLBACKS[cat];
  }

  return CATEGORY_IMAGE_FALLBACKS["General Healthcare"];
}
